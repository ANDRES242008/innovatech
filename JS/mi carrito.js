    function getCart() {
      // Si usas localStorage:
      return JSON.parse(localStorage.getItem('shoppingCart')) || [];
      // Si usas window.cart, cambia esto por window.cart.items
    }

    function saveCart(cart) {
      localStorage.setItem('shoppingCart', JSON.stringify(cart));
    }

